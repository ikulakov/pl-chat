/**
 * Идентификаторы как отдельные типы, а не голые строки.
 *
 * На одном элементе ленты лежат три строки с разной семантикой — `localId` (ключ React и якорь
 * optimistic-обновлений), `eventId` (id события на сервере либо плейсхолдер `optimistic:…`) и
 * `txnId` (ключ идемпотентности `PUT /send`). Перепутать их местами компилятор без брендов не
 * мешает, а цена ошибки — дубль в ленте или незарезолвленный черновик.
 *
 * Бренд **мягкий**: поле `__id` необязательное, поэтому обычная строка присваивается любому id
 * свободно, а вот id одного вида другому — уже нет. Это сознательный размен. Жёсткий бренд
 * (`unique symbol`) заставил бы обернуть конструктором каждый строковый литерал в тестах и
 * фикстурах — порядка пятисот мест, — но поймал бы ровно один дополнительный класс ошибки:
 * свежесочинённую строку не в том поле. В проде такие строки почти не встречаются: id приходят
 * из мапперов, стора и элементов ленты, то есть уже типизированными, и между собой их путают —
 * это мягкий бренд и ловит.
 *
 * Родство видов выражено самим типом: `LocalId` принимает `EventId`, потому что у события с
 * сервера ключом ленты служит его же id. Обратно — нельзя, и это важная половина: `LocalId`
 * черновика (uuid) серверу ничего не адресует.
 */
type Id<Kind extends string> = { readonly __id?: Kind }

/** `$abc…` — id события в комнате. У черновика до ответа сервера — `optimistic:{localId}`. */
export type EventId = string & Id<'EventId'>

/**
 * Ключ элемента ленты на клиенте: стабильный React-ключ и якорь optimistic-обновлений.
 *
 * **Надтип `EventId`** — объединение в бренде не опечатка. У черновика это свой uuid, у события
 * с сервера — его же `event_id`: другого ключа у него нет, а `event_id` уникален и стабилен
 * между перезагрузками. Поэтому любой `EventId` годится в `LocalId` без конверсии, а вот
 * `LocalId` в `EventId` не проходит — uuid черновика сервер не знает.
 */
export type LocalId = string & Id<'LocalId' | 'EventId'>

/** Ключ идемпотентности `PUT /send`; по нему `mergeTimeline` резолвит черновик в событие. */
export type TxnId = string & Id<'TxnId'>

/** `@user:server` — участник комнаты. */
export type UserId = string & Id<'UserId'>

/** `!room:server` — комната = один Communication. */
export type RoomId = string & Id<'RoomId'>

/** Часть `mxc://server/{mediaId}`: файл, стикер или анимация эмодзи. */
export type MediaId = string & Id<'MediaId'>
