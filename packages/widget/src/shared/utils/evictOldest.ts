/**
 * Держит кэш в пределах `max` записей, выбрасывая самые давние. Кэши считают записи, а не байты:
 * вес записи в каждом из них ограничен сверху (миниатюра — по построению, свой файл — лимитом
 * композера, эмодзи — лимитом формата TGS), поэтому число записей и есть предсказуемый потолок.
 */
export function evictOldest<T>(entries: Map<string, T>, max: number): void {
  // Map хранит порядок вставки — он же порядок вытеснения.
  for (const oldest of entries.keys()) {
    if (entries.size <= max) break
    entries.delete(oldest)
  }
}
