/**
 * Локальные фича-флаги виджета. Переключаются правкой этого файла и пересборкой —
 * серверного источника (`/capabilities`) виджет пока не читает.
 *
 * Флаг гасит только точку входа в UI. Разбор входящих событий, экшены и транспорт не
 * трогаются: чужие реакции продолжают приходить в стор, просто не рисуются, — чтобы
 * включение флага обратно не требовало переподключения сессии.
 */
export interface WidgetFeatures {
  /**
   * Эмодзи целиком: кнопка пикера в композере (вместе с вкладкой стикеров) и подмена
   * символов анимациями пака в ленте.
   *
   * Выключение снимает и стоимость фичи: без индекса пака `splitEmoji` оставляет текст
   * текстом, `AnimatedEmoji`/`InlineEmoji` не монтируются, и Lottie-движок не грузится —
   * отдельный флаг для него не нужен, импорт и так ленивый. Эмодзи оператора при этом
   * рисуются системным шрифтом. Стикеры оператора не затрагиваются.
   */
  emoji: boolean
  /** Реакции: чипы под сообщением и панель быстрых реакций в меню сообщения. */
  reactions: boolean
}

export const FEATURES: WidgetFeatures = {
  emoji: false,
  reactions: false,
}
