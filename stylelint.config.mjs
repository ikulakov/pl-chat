/**
 * Проверка CSS на фичи новее минимальной поддерживаемой версии браузера.
 * Планка объявлена в .browserslistrc и обязана совпадать с build.target
 * в packages/widget/vite.config.ts.
 *
 * ВАЖНО про охват: плагин ходит в caniuse, поэтому видит не всё. color-mix()
 * в caniuse отсутствует (он только в MDN BCD) и этой проверкой НЕ ловится —
 * его стережёт отдельное правило ниже. Значит зелёный stylelint не означает
 * «фич новее планки нет»: он снимает распространённый класс ошибок,
 * но не заменяет ревью.
 */
export default {
  plugins: ['stylelint-no-unsupported-browser-features'],
  rules: {
    // color-mix() новее планки (Chromium 111 / Safari 16.2), но с литеральными
    // аргументами его считает Lightning CSS на сборке — в dist уезжает hex, и
    // браузеру функция не достаётся. С var() или currentColor вычислить нечего:
    // такой color-mix() дойдёт до браузера и ниже планки схлопнет свойство.
    // Поэтому запрещена только динамическая форма. Проверять глазами dist не
    // надо — форма записи и решает. Пишется формулами в styles/variables.css.
    'declaration-property-value-disallowed-list': [
      { '/.*/': [/color-mix\([^;]*(var\(|currentcolor)/i] },
      {
        message:
          'color-mix() только с литеральными цветами — var()/currentColor на сборке не вычислить',
      },
    ],
    'plugin/no-unsupported-browser-features': [
      true,
      {
        severity: 'error',
        // В этот список попадает только то, что безопасно ВСЕГДА — иначе игнор
        // глушит не известные места, а любое будущее использование, и линтер
        // перестаёт быть линтером. Разовые исключения оформляются
        // stylelint-disable-next-line по месту, с обоснованием.
        ignore: [
          // Вложенность разворачивает Lightning CSS на сборке независимо от
          // таргета — проверено: в dist/assets/*.css нет ни одного '&'.
          'css-nesting',

          // scrollbar-width/color: на iOS не применяются, скроллбар рисуется
          // системный. Косметика при любом использовании.
          'css-scrollbar',

          // resize на textarea: iOS игнорирует ручку ресайза. Косметика.
          'css-resize',

          // overflow-anchor: в WebKit не поддержан и не будет. Якорение скролла
          // на iOS отсутствует в принципе — лента это переживает, положение
          // держит useChatScroll своими средствами.
          'css-overflow-anchor',

          // touch-action caniuse помечает только для десктопного Safari — там нет
          // тач-ввода, свойству нечего делать. На iOS Safari 16+ работает.
          'css-touch-action',

          // css-has и css-masks сознательно НЕ здесь: у них деградация зависит
          // от конкретного применения. :has() на отступах переживём, :has() на
          // видимости элемента — нет; mask без -webkit-префикса ломается там,
          // где с префиксом работает. Каждое место разбирается отдельно.
        ],
      },
    ],
  },
}
